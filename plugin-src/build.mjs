// Bundle the tagger (with @babel/parser + magic-string inlined) into a single
// self-contained ESM file, and copy the overlay, into src-tauri/assets/ where
// the Rust core embeds them via include_str!.
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(here, "..", "src-tauri", "assets");
fs.mkdirSync(outDir, { recursive: true });

await build({
  entryPoints: [path.join(here, "tagger.mjs")],
  outfile: path.join(outDir, "dedup-tagger.mjs"),
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node18",
  minify: true,
  legalComments: "none",
  banner: {
    js: "// dedup tagger bundle — generated by plugin-src/build.mjs; do not edit.",
  },
});

fs.copyFileSync(
  path.join(here, "overlay.js"),
  path.join(outDir, "dedup-overlay.js"),
);

const size = fs.statSync(path.join(outDir, "dedup-tagger.mjs")).size;
console.log(`built assets/dedup-tagger.mjs (${(size / 1024).toFixed(0)} KB) + dedup-overlay.js`);
