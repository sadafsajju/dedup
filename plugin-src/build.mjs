// Bundle the tagger (with @babel/parser + magic-string inlined) into a single
// self-contained ESM file, and copy the overlay, into src-tauri/assets/ where
// the Rust core embeds them via include_str!.
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(here, "..", "src-tauri", "assets");
fs.mkdirSync(outDir, { recursive: true });

const shared = {
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node18",
  minify: true,
  legalComments: "none",
};

await build({
  ...shared,
  entryPoints: [path.join(here, "tagger.mjs")],
  outfile: path.join(outDir, "dedup-tagger.mjs"),
  banner: {
    js: "// dedup tagger bundle — generated by plugin-src/build.mjs; do not edit.",
  },
});

await build({
  ...shared,
  entryPoints: [path.join(here, "writeback.mjs")],
  outfile: path.join(outDir, "dedup-writeback.mjs"),
  banner: {
    js: "// dedup write-back bundle — generated by plugin-src/build.mjs; do not edit.",
  },
});

// The static-site dev server (plain HTML projects). Bundled with parse5 and
// magic-string inlined for the same reason as everything else here: it runs
// against the user's folder, which for a static site has no node_modules at
// all to resolve anything from.
await build({
  ...shared,
  entryPoints: [path.join(here, "serve.mjs")],
  outfile: path.join(outDir, "dedup-serve.mjs"),
  banner: {
    js: "// dedup static server bundle — generated by plugin-src/build.mjs; do not edit.",
  },
});

// Next.js: the config wrapper stays ESM (next.config.mjs imports it), while
// the tagging loader is CommonJS because that is how webpack resolves loaders.
await build({
  ...shared,
  entryPoints: [path.join(here, "next.mjs")],
  outfile: path.join(outDir, "dedup-next.mjs"),
  banner: {
    js: "// dedup Next.js wrapper — generated by plugin-src/build.mjs; do not edit.",
  },
});

await build({
  ...shared,
  format: "cjs",
  entryPoints: [path.join(here, "next-loader.mjs")],
  outfile: path.join(outDir, "dedup-next-loader.cjs"),
  banner: {
    js: "// dedup Next.js tagging loader — generated by plugin-src/build.mjs; do not edit.",
  },
});

// The wrapper's type declaration rides along: a TypeScript next.config under
// `strict` that imports an untyped .mjs fails its own typecheck.
fs.copyFileSync(
  path.join(here, "next.d.mts"),
  path.join(outDir, "dedup-next.d.mts"),
);

// The overlay runs in the page, so it is one classic script — but it is
// bundled rather than copied, so the rule for what a marquee selects can live
// in a module of its own (marquee.mjs) that a test can import. Not minified:
// it is the file a user sees in their devtools when something goes wrong.
await build({
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  legalComments: "none",
  entryPoints: [path.join(here, "overlay.js")],
  outfile: path.join(outDir, "dedup-overlay.js"),
});

const size = fs.statSync(path.join(outDir, "dedup-tagger.mjs")).size;
console.log(`built assets/dedup-tagger.mjs (${(size / 1024).toFixed(0)} KB) + dedup-overlay.js`);
